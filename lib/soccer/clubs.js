// 별점 (0.5 단위, 최대 5)
export function clubStars(club) {
  const o = club.rating[0];
  return o >= 86 ? 5 : o >= 83 ? 4.5 : o >= 80 ? 4 : o >= 77 ? 3.5 : o >= 74 ? 3 : 2.5;
}

// 컵 대회용: 두 팀의 경기 결과를 능력치로 빠르게 계산 (AI끼리 경기)
function poisson(lambda) {
  let k = 0, p = 1;
  const L = Math.exp(-lambda);
  do { k++; p *= Math.random(); } while (p > L);
  return k - 1;
}

export function quickResult(aIdx, bIdx) {
  const ra = CLUBS[aIdx].rating[0], rb = CLUBS[bIdx].rating[0];
  const ga = poisson(1.35 * Math.exp((ra - rb) / 12));
  const gb = poisson(1.35 * Math.exp((rb - ra) / 12));
  return { ga, gb };
}

// 승부차기 (5명씩, 같으면 서든데스)
export function penaltyShootout(aIdx, bIdx) {
  const ra = CLUBS[aIdx].rating[0], rb = CLUBS[bIdx].rating[0];
  const pa = 0.74 + (ra - rb) / 200, pb = 0.74 + (rb - ra) / 200;
  let a = 0, b = 0;
  for (let i = 0; i < 5; i++) { if (Math.random() < pa) a++; if (Math.random() < pb) b++; }
  while (a === b) { const x = Math.random() < pa, y = Math.random() < pb; a += x; b += y; }
  return { pa: a, pb: b };
}
