export const CLUBS = LEAGUES.flatMap(l => l.teams.map(t => ({ ...t, players: ROSTERS[t.short] ? ROSTERS[t.short].players : [...t.players, ...benchOf(t.short)], league: l.id, crest: `/crests/${t.short}.png` })));
export const clubIndex = (short) => CLUBS.findIndex(c => c.short === short);

// 상대와 유니폼 색이 비슷하면 원정 유니폼으로 바꿈
function colorDist(a, b) {
  const p = h => [1, 3, 5].map(i => parseInt(h.slice(i, i + 2), 16));
  const [r1, g1, b1] = p(a), [r2, g2, b2] = p(b);
  return Math.hypot(r1 - r2, g1 - g2, b1 - b2);
}

export function matchTeams(homeIdx, awayIdx) {
  const home = CLUBS[homeIdx], away = CLUBS[awayIdx];
  const hk = home.kits.home;
  let ak = away.kits.home;
  if (colorDist(hk.shirt, ak.shirt) < 120 || colorDist(hk.shorts, ak.shorts) + colorDist(hk.shirt, ak.shirt) < 200) ak = away.kits.away;
  const info = (club, k) => ({
    name: club.name, short: club.short, players: club.players, kit: k, gk: club.gk, crest: club.crest, rating: club.rating, league: club.league,
    color: k.shirt, color2: k.trim,
  });
  return [info(home, hk), info(away, ak)];
}

