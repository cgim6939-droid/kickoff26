// 자동 결정: 이름을 씨앗으로 한 고정 난수
function pickWeighted(r, weights) {
  let s = 0;
  for (let i = 0; i < weights.length; i++) { s += weights[i]; if (r < s) return i; }
  return weights.length - 1;
}
function autoLook(name, num) {
  const key = String(name) + num;
  const skin = pickWeighted(hash01(key, 11), [0.2, 0.4, 0.17, 0.09, 0.09, 0.05]);
  const dark = skin >= 4;
  const style = pickWeighted(hash01(key, 12), dark ? [0.1, 0.35, 0.3, 0.02, 0.0, 0.0, 0.15, 0.04, 0.02, 0, 0.02] : [0.04, 0.05, 0.5, 0.18, 0.1, 0.0, 0.04, 0, 0, 0.03, 0.06]);
  const color = dark ? 0 : pickWeighted(hash01(key, 13), [0.28, 0.3, 0.2, 0.1, 0.07, 0.02, 0.02, 0.01]);
  const beard = pickWeighted(hash01(key, 14), [0.45, 0.4, 0.15]);
  return { skin, hair: style, color, beard };
}

export function lookOf(short, index, name, num) {
  const row = (ROSTERS[short] && ROSTERS[short].looks[index]) || (L[short] && L[short][index]);
  if (row && row !== 'x') {
    const [s, h, c, b] = row.split(',').map(Number);
    return { skin: s, hair: h, color: c, beard: b };
  }
  return autoLook(name, num);
}

// 화면/모델이 쓰기 편한 형태로 풀어 줌
export function resolveLook(short, index, name, num) {
  const l = lookOf(short, index, name, num);
  return {
    ...l,
    skinHex: SKIN_TONES[l.skin], hairHex: HAIR_COLORS[l.color],
    hairStyle: HAIR_STYLES[l.hair] || 'short', beardStyle: BEARD_STYLES[l.beard] || 'none',
  };
}
